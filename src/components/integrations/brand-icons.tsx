// The tint behind each mark, so the tile reads as that brand at a glance.
// null = no tint (the neutral tile): black marks and the gradient Instagram.
const TILE_TINT: Record<BrandKey, string | null> = {
  instagram: "#E4405F",
  facebook: "#0866FF",
  "meta-ads": "#0467DF",
  telegram: "#26A5E4",
  ga4: "#E37400",
  "search-console": "#458CF5",
  tiktok: null,
  linkedin: "#0A66C2",
  x: null,
};

const INSTAGRAM_GRADIENT_ID = "brand-instagram-gradient";

export function BrandIcon({
  brand,
  className,
}: {
  brand: BrandKey;
  className?: string;
}) {
  const common = {
    "aria-hidden": true,
    focusable: false,
    className: cn("shrink-0", className),
  } as const;

  switch (brand) {
    case "instagram":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <defs>
            <linearGradient
              id={INSTAGRAM_GRADIENT_ID}
              gradientUnits="userSpaceOnUse"
              x1="2"
              y1="24"
              x2="22"
              y2="0"
            >
              <stop offset="0" stopColor="#FEDA75" />
              <stop offset="0.25" stopColor="#FA7E1E" />
              <stop offset="0.5" stopColor="#D62976" />
              <stop offset="0.75" stopColor="#962FBF" />
              <stop offset="1" stopColor="#4F5BD5" />
            </linearGradient>
          </defs>
          {/* The glyph is cut out of the square; white behind it shows through. */}
          <rect x="1.4" y="1.4" width="21.2" height="21.2" rx="5.5" fill="#fff" />
          <path d={PATH.instagram} fill={`url(#${INSTAGRAM_GRADIENT_ID})`} />
        </svg>
      );
    case "facebook":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <circle cx="12" cy="12" r="11.5" fill="#fff" />
          <path d={PATH.facebook} fill="#0866FF" />
        </svg>
      );
    case "meta-ads":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <path d={PATH.meta} fill="#0467DF" />
        </svg>
      );
    case "telegram":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <circle cx="12" cy="12" r="11.5" fill="#fff" />
          <path d={PATH.telegram} fill="#26A5E4" />
        </svg>
      );
    case "ga4":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <path d={PATH.ga4} fill="#E37400" />
        </svg>
      );
    case "search-console":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <path d={PATH.gsc} fill="#458CF5" />
        </svg>
      );
    case "tiktok":
      return (
        <svg viewBox="0 0 24 24" overflow="visible" {...common}>
          {/* TikTok's mark is the note with a cyan and a red offset behind it. */}
          <path d={PATH.tiktok} fill="#25F4EE" transform="translate(-0.7 -0.7)" />
          <path d={PATH.tiktok} fill="#FE2C55" transform="translate(0.7 0.7)" />
          <path d={PATH.tiktok} fill="currentColor" />
        </svg>
      );
    case "linkedin":
      return (
        <svg viewBox="0 32 448 448" {...common}>
          <rect x="8" y="40" width="432" height="432" rx="40" fill="#fff" />
          <path d={PATH.linkedin} fill="#0A66C2" />
        </svg>
      );
    case "x":
      return (
        <svg viewBox="0 0 24 24" {...common}>
          <path d={PATH.x} fill="currentColor" />
        </svg>
      );
  }
}

// The rounded tile a connector's mark sits on, tinted with the brand color.
export function BrandTile({
  brand,
  className,
  iconClassName,
}: {
  brand: BrandKey;
  className?: string;
  iconClassName?: string;
}) {
  const tint = TILE_TINT[brand];
  const style: CSSProperties | undefined = tint
    ? { backgroundColor: `color-mix(in oklab, ${tint} 12%, transparent)` }
    : undefined;
  return (
    <span
      style={style}
      className={cn(
        "flex shrink-0 items-center justify-center rounded-lg text-foreground",
        !tint && "bg-muted",
        className,
      )}
    >
      <BrandIcon brand={brand} className={iconClassName} />
    </span>
  );
}
